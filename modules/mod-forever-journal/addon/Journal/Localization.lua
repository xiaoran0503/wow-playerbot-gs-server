-- Journal - Localization.lua
--
-- 中文（简体）语言包。界面文字全部写成 L["英文原文"]，英文原文就是查表的键。
--
-- 为什么这么写：
--   * 想改某个说法，只改这个文件，不用碰逻辑代码。
--   * 键查不到时 __index 会把键原样返回，最坏情况是露出英文，
--     永远不会变成空白 —— 这是"汉化后不显示"最常见的成因。
--   * 以 # 开头的键是符号键（长句 / 带 %s 的模板），见文件末尾。
--
-- 文件必须是 UTF-8 无 BOM。带 BOM 客户端会报 "unexpected symbol near '<\239>'"
-- 并直接放弃整个插件。
--
-- 注意：服务端下发的数据（副本名、首领名、物品名、任务名、掉落说明）不走这张表，
-- 那些是服务端数据库里的语言，客户端只负责显示。要让它们也变中文，
-- 得给服务端的 world 库导入中文数据（汉化补丁包），跟插件无关。

